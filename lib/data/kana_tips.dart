  // Метод для экрана ошибки
  static String getSmartTip(String char, String correctRomaji, String? selectedRomaji) {
    if (selectedRomaji != null) {
      final selectedClean = selectedRomaji.split(' ').last.replaceAll('(', '').replaceAll(')', '').toLowerCase();
      final correctClean = correctRomaji.toLowerCase();

      final pair1 = '${correctClean}_$selectedClean';
      final pair2 = '${selectedClean}_$correctClean';

      if (confusionTips.containsKey(pair1)) return confusionTips[pair1]!;
      if (confusionTips.containsKey(pair2)) return confusionTips[pair2]!;

      final baseTip = explanations[char] ?? 'Этот знак читается как "$correctRomaji".';
      return 'Ты выбрал "$selectedRomaji", но правильный ответ — "$correctRomaji". $baseTip';
    }
    return explanations[char] ?? 'Этот знак читается как "$correctRomaji".';
  }

  // Метод для подсказки ПЕРЕД ответом
  static String getHint(String char, String correctRomaji) {
    final tip = explanations[char] ?? '';
    if (tip.isEmpty) return 'Попробуй вспомнить, как этот знак звучит.';
    return 'Подсказка от Аи: $tip';
  }
